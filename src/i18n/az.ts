// Number suffixes follow vowel harmony with the last spoken word of the number:
// 3 üç → 3-cü, 6 altı → 6-cı, 10 on → 10-dan, 20 iyirmi → 20-dən.
type Harmony = 'i' | 'ı' | 'u' | 'ü';
const UNITS: Harmony[] = ['i', 'i', 'i', 'ü', 'ü', 'i', 'ı', 'i', 'i', 'u']; // 0 unused, 1 bir … 9 doqquz
const TENS: Harmony[] = ['i', 'u', 'i', 'u', 'ı', 'i', 'ı', 'i', 'i', 'ı']; // 10 on, 20 iyirmi … 90 doxsan
function harmony(raw: string | number): Harmony {
  const n = Math.abs(Math.trunc(Number(raw)));
  if (n === 0) return 'ı'; // sıfır
  if (n % 10) return UNITS[n % 10];
  if (n % 100) return TENS[(n % 100) / 10];
  if (n % 1000) return 'ü'; // yüz
  if (n % 1_000_000) return 'i'; // min
  return 'u'; // milyon
}
/** Ordinal: 1-ci, 3-cü, 6-cı, 9-cu. */
const ord = (raw: string | number, shown: string | number) => `${shown}-c${harmony(raw)}`;
/** Ablative: 10-dan, 20-dən. */
const from = (raw: string | number, shown: string | number) => `${shown}-d${harmony(raw) === 'ı' || harmony(raw) === 'u' ? 'a' : 'ə'}n`;
const ordOf = (r: Params, f: Params, k: string) => ord(r[k], f[k]);

