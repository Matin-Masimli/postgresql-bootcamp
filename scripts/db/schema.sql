-- PostgreSQL Bootcamp practice database: "Atlas Mercantile", a fictional online retailer.
-- Single source of truth for the DDL. Indexes live in indexes.sql and are created after loading.
-- Reference date ("today") for every question: 2025-06-30. Data spans 2021-01-01 .. 2025-06-30 (UTC).

-- ───────────── Reference data (identical in the main and hidden datasets) ─────────────

CREATE TABLE countries (
  country_id       smallint PRIMARY KEY,
  iso_code         char(2)  NOT NULL UNIQUE,
  name             text     NOT NULL UNIQUE,
  region           text     NOT NULL,
  currency         char(3)  NOT NULL,
  default_timezone text     NOT NULL
);
COMMENT ON TABLE countries IS 'Countries we sell to or source from. A few have no customers at all.';
COMMENT ON COLUMN countries.region IS 'Continent-level grouping, e.g. Europe, North America, Asia.';
COMMENT ON COLUMN countries.default_timezone IS 'IANA time zone name of the capital, e.g. Europe/Berlin.';

CREATE TABLE categories (
  category_id integer PRIMARY KEY,
  parent_id   integer REFERENCES categories (category_id),
  name        text    NOT NULL,
  slug        text    NOT NULL UNIQUE
);
COMMENT ON TABLE categories IS 'Product category tree, up to 4 levels deep. Root categories have parent_id NULL. Names are not unique (e.g. two "Shoes" categories); slugs are.';

CREATE TABLE departments (
  department_id smallint PRIMARY KEY,
  name          text NOT NULL UNIQUE,
  location      text,
  budget        numeric(12,2)
);
COMMENT ON TABLE departments IS 'Company departments. One department currently has no employees.';

-- ───────────── Business data (different in the main and hidden datasets) ─────────────

CREATE TABLE suppliers (
  supplier_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          text     NOT NULL,
  country_id    smallint REFERENCES countries (country_id),
  contact_email text,
  rating        numeric(2,1) CHECK (rating BETWEEN 1 AND 5),
  created_at    date     NOT NULL
);
COMMENT ON TABLE suppliers IS 'Companies that supply our products. Some supply nothing we currently list.';
COMMENT ON COLUMN suppliers.rating IS 'Internal quality score 1.0-5.0; NULL = not yet rated.';

CREATE TABLE products (
  product_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku             text          NOT NULL UNIQUE,
  name            text          NOT NULL,
  category_id     integer       NOT NULL REFERENCES categories (category_id),
  supplier_id     integer       REFERENCES suppliers (supplier_id),
  price           numeric(10,2) NOT NULL CHECK (price >= 0),
  cost            numeric(10,2) CHECK (cost >= 0),
  weight_kg       numeric(6,3),
  launched_at     date          NOT NULL,
  discontinued_at date,
  CHECK (discontinued_at IS NULL OR discontinued_at >= launched_at)
);
COMMENT ON TABLE products IS 'Catalogue. Products are always in a leaf category. Some were never sold.';
COMMENT ON COLUMN products.price IS 'Current list price. Historic order lines may have been sold at an older price (see order_items.unit_price).';
COMMENT ON COLUMN products.cost IS 'Our purchase cost per unit; NULL when unknown.';
COMMENT ON COLUMN products.discontinued_at IS 'Last day the product could be ordered; NULL = still on sale.';

CREATE TABLE customers (
  customer_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name       text        NOT NULL,
  last_name        text        NOT NULL,
  email            text,
  phone            text,
  birth_date       date,
  gender           char(1),
  city             text,
  country_id       smallint    REFERENCES countries (country_id),
  timezone         text,
  signup_at        timestamptz NOT NULL,
  marketing_opt_in boolean     NOT NULL DEFAULT false,
  referred_by      integer     REFERENCES customers (customer_id)
);
COMMENT ON TABLE customers IS 'Registered customers. Text was typed by humans: inconsistent case, stray spaces, mixed phone formats, NULLs. About 10% never ordered.';
COMMENT ON COLUMN customers.gender IS 'F, M, X or NULL (not provided).';
COMMENT ON COLUMN customers.timezone IS 'Customer''s IANA time zone; NULL when unknown.';
COMMENT ON COLUMN customers.referred_by IS 'Customer who referred this one (referral chains can be several levels deep).';

CREATE TABLE employees (
  employee_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name       text          NOT NULL,
  last_name        text          NOT NULL,
  email            text          NOT NULL UNIQUE,
  job_title        text          NOT NULL,
  department_id    smallint      REFERENCES departments (department_id),
  manager_id       integer       REFERENCES employees (employee_id),
  hire_date        date          NOT NULL,
  termination_date date,
  salary           numeric(10,2) NOT NULL CHECK (salary > 0),
  commission_pct   numeric(4,3)  CHECK (commission_pct BETWEEN 0 AND 1)
);
COMMENT ON TABLE employees IS 'Staff, organised as a 5-level hierarchy under the CEO (manager_id NULL).';
COMMENT ON COLUMN employees.salary IS 'Current (or final, if terminated) annual salary.';
COMMENT ON COLUMN employees.commission_pct IS 'Sales commission as a fraction, e.g. 0.050 = 5%. NULL for non-commissioned staff.';
COMMENT ON COLUMN employees.termination_date IS 'Last working day; NULL = still employed.';

CREATE TABLE salary_history (
  employee_id    integer       NOT NULL REFERENCES employees (employee_id),
  effective_from date          NOT NULL,
  effective_to   date,
  salary         numeric(10,2) NOT NULL,
  change_reason  text,
  PRIMARY KEY (employee_id, effective_from),
  CHECK (effective_to IS NULL OR effective_to >= effective_from)
);
COMMENT ON TABLE salary_history IS 'One row per salary period. effective_to is inclusive; NULL = current period.';

CREATE TABLE orders (
  order_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id     integer      NOT NULL REFERENCES customers (customer_id),
  sales_rep_id    integer      REFERENCES employees (employee_id),
  ordered_at      timestamptz  NOT NULL,
  status          text         NOT NULL CHECK (status IN ('pending','processing','shipped','delivered','cancelled','returned')),
  channel         text         NOT NULL CHECK (channel IN ('web','mobile','phone','marketplace')),
  ship_country_id smallint     REFERENCES countries (country_id),
  shipping_fee    numeric(8,2) NOT NULL DEFAULT 0,
  coupon_code     text,
  shipped_at      timestamptz,
  delivered_at    timestamptz
);
COMMENT ON TABLE orders IS 'Order headers. The order value is the sum of its order_items plus shipping_fee.';
COMMENT ON COLUMN orders.sales_rep_id IS 'Employee credited with the sale; NULL for self-service orders.';
COMMENT ON COLUMN orders.coupon_code IS 'Code typed by the customer at checkout, as entered (case and spaces vary).';
COMMENT ON COLUMN orders.shipped_at IS 'When the first shipment left the warehouse; NULL if not shipped.';
COMMENT ON COLUMN orders.delivered_at IS 'When the last shipment was delivered; NULL if not (yet) delivered.';

CREATE TABLE order_items (
  order_item_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id      integer       NOT NULL REFERENCES orders (order_id),
  line_no       smallint      NOT NULL,
  product_id    integer       NOT NULL REFERENCES products (product_id),
  quantity      integer       NOT NULL CHECK (quantity > 0),
  unit_price    numeric(10,2) NOT NULL CHECK (unit_price >= 0),
  discount      numeric(4,3)  NOT NULL DEFAULT 0 CHECK (discount BETWEEN 0 AND 0.9),
  UNIQUE (order_id, line_no)
);
COMMENT ON TABLE order_items IS 'Order lines. Line value = quantity * unit_price * (1 - discount).';
COMMENT ON COLUMN order_items.discount IS 'Fractional discount on the line, e.g. 0.150 = 15% off.';

CREATE TABLE payments (
  payment_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id   integer       NOT NULL REFERENCES orders (order_id),
  paid_at    timestamptz   NOT NULL,
  method     text          NOT NULL CHECK (method IN ('card','paypal','bank_transfer','gift_card','wallet')),
  amount     numeric(10,2) NOT NULL CHECK (amount >= 0),
  status     text          NOT NULL CHECK (status IN ('captured','failed','refunded'))
);
COMMENT ON TABLE payments IS 'Payment attempts. Failed attempts are kept. A refund is its own row with status refunded and a positive amount.';

CREATE TABLE shipments (
  shipment_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id        integer      NOT NULL REFERENCES orders (order_id),
  carrier         text         NOT NULL,
  tracking_number text,
  shipped_at      timestamptz  NOT NULL,
  delivered_at    timestamptz,
  shipping_cost   numeric(8,2)
);
COMMENT ON TABLE shipments IS 'Parcels. Most orders ship in one parcel, some are split into two.';
COMMENT ON COLUMN shipments.shipping_cost IS 'What the carrier charged us; NULL when the invoice is missing.';

CREATE TABLE returns (
  return_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_item_id integer       NOT NULL REFERENCES order_items (order_item_id),
  requested_at  timestamptz   NOT NULL,
  reason        text,
  quantity      integer       NOT NULL CHECK (quantity > 0),
  refund_amount numeric(10,2),
  status        text          NOT NULL CHECK (status IN ('requested','approved','rejected','refunded'))
);
COMMENT ON TABLE returns IS 'Return requests per order line. reason is free text typed by the customer.';
COMMENT ON COLUMN returns.refund_amount IS 'Amount refunded or approved; NULL while requested or if rejected.';

CREATE TABLE reviews (
  review_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id    integer     NOT NULL REFERENCES products (product_id),
  customer_id   integer     REFERENCES customers (customer_id),
  rating        smallint    NOT NULL CHECK (rating BETWEEN 1 AND 5),
  title         text,
  body          text,
  created_at    timestamptz NOT NULL,
  helpful_votes integer     NOT NULL DEFAULT 0 CHECK (helpful_votes >= 0)
);
COMMENT ON TABLE reviews IS 'Product reviews. customer_id is NULL for anonymised (deleted) accounts. Not every reviewer bought the product.';

CREATE TABLE user_logins (
  login_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id  integer     NOT NULL REFERENCES customers (customer_id),
  logged_in_at timestamptz NOT NULL,
  device       text        NOT NULL CHECK (device IN ('desktop','ios','android','tablet')),
  ip_address   inet,
  success      boolean     NOT NULL
);
COMMENT ON TABLE user_logins IS 'Website/app login attempts, tracked since 2023-01-01. A customer can log in several times a day.';

CREATE TABLE staging_customer_import (
  import_row_id      integer PRIMARY KEY,
  source_file        text        NOT NULL,
  imported_at        timestamptz NOT NULL,
  full_name          text,
  email              text,
  phone              text,
  signup_date_raw    text,
  country_raw        text,
  lifetime_value_raw text
);
COMMENT ON TABLE staging_customer_import IS 'Raw rows loaded from CRM CSV exports, untouched: duplicates, inconsistent formats and junk included.';
COMMENT ON COLUMN staging_customer_import.signup_date_raw IS 'Date as text. Each source_file uses its own format: crm_export_2024_*.csv ISO "YYYY-MM-DD" or "DD/MM/YYYY", legacy_dump.csv "Mon DD, YYYY".';
COMMENT ON COLUMN staging_customer_import.lifetime_value_raw IS 'Money as text, e.g. "1234.50", "$1,234.50", "n/a" or empty.';
